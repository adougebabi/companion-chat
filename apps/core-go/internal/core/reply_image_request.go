const replyImageRequestName = "reply.image.request"

func replyWriterDefinitions(input ReplyContextInput) []CapabilityDefinition {
	if input.Scene == replySceneMoment || input.StyleRepair {
		return nil
	}
	for _, fact := range input.ToolFacts {
		if stringValue(fact["kind"]) == "media_action_result" || stringValue(fact["kind"]) == "private_candidate_text" {
			return nil
		}
	}
	definitions := []CapabilityDefinition{}
	if input.CapabilityFacts["image_generation_registered"] == true {
		definitions = append(definitions, (&replyImageRequestTool{expressionVersion: input.ExpressionVersion}).Definition())
	}
	if input.CapabilityFacts["persona_detail_registered"] == true && replyUsesTextChatProtocol(input.ExpressionVersion) {
		definitions = append(definitions, personaDetailCapabilityDefinition())
	}
	return definitions
}

// This private Writer tool records an actual draft handoff, not generated bytes
// or a publication. The existing reply-owned media pipeline executes that
// handoff under the original source/permission/Kev fences after preparation.
type replyImageRequestTool struct {
	mu                sync.Mutex
	requests          []ReplyMediaRequest
	byCall            map[string]string
	expressionVersion string
}

func (t *replyImageRequestTool) Definition() CapabilityDefinition {
	description := "Request a real image/selfie for this chat reply draft. Describe the desired scene in intent; the server hands it to the image generator. Call this tool ONLY when the user explicitly asks for a photo/selfie/picture, or when agreeing to send one. Never call during ordinary text chat. Do not print SVG/path data or claim sending in text; finish with ordinary persona text. At most two requests."
	if firstString(t.expressionVersion, factOnlyReplyPromptVersion) == factOnlyReplyV7PromptVersion {
		description = "当用户要求看图、生成图片或发送照片时，必须且只能调用此工具。绝对不要在 content 中用文字描述图片的样子，直接调用！当你决定主动分享图片或自拍时，也必须调用此工具。在 intent 中描述画面；每次回复最多请求两张。工具仅登记请求，不代表图片已生成或发送；按真实结果继续回复。"
	} else if firstString(t.expressionVersion, factOnlyReplyPromptVersion) == factOnlyReplyV8PromptVersion {
		description = "需要拍照、自拍或发送当下画面时，调用此工具并在 intent 中描述画面；普通文字闲聊不调用。此工具只登记请求，不代表图片已生成或发送；不要在正文伪造附件。每次回复最多请求两张。"
	}
	return CapabilityDefinition{Name: replyImageRequestName, Version: "v1", Type: CapabilityTypeQuery,
		Description:  description,
		InputSchema:  objectSchema(map[string]any{"intent": map[string]any{"type": "string", "minLength": 1, "maxLength": 2048}}, []string{"intent"}, false),
		OutputSchema: openObjectSchema(), Surfaces: []CapabilitySurface{CapabilitySurfaceConversation}, SupportsCancel: true,
		SideEffectClass: "read_only", ConcurrencyClass: "parallel", FailurePolicy: FailurePolicyOptionalInternal, SuccessBoundary: "draft_request_recorded"}
}
func (*replyImageRequestTool) RequiredContext() []ContextSlot { return nil }
func (t *replyImageRequestTool) Execute(ctx context.Context, inv CapabilityInvocation, _ CapabilityContext) (CapabilityResult, error) {
	if err := ctx.Err(); err != nil {
		return CapabilityResult{}, err
	}
	normalized, err := normalizeNativeModelArguments(inv.Arguments, t.Definition())
	if err != nil {
		return handledCapabilityResult(inv, "invalid_arguments", "needs_input", nil), nil
	}
	inv.Arguments = normalized
	var args struct {
		Intent string `json:"intent"`
	}
	if err := json.Unmarshal(inv.Arguments, &args); err != nil {
		return CapabilityResult{}, err
	}
	args.Intent = strings.TrimSpace(args.Intent)
	if args.Intent == "" {
		return CapabilityResult{}, ErrInvalidArguments
	}
	t.mu.Lock()
	defer t.mu.Unlock()
	if t.byCall == nil {
		t.byCall = map[string]string{}
	}
	if prior, exists := t.byCall[inv.CallID]; exists {
		if prior != args.Intent {
			return handledCapabilityResult(inv, "reply_media_request_replayed", "no_change", map[string]any{"generated": false, "sent": false, "ignored_payload_change": true}), nil
		}
	} else {
		if len(t.requests) >= 2 {
			return handledCapabilityResult(inv, "reply_media_request_limit", "no_change", map[string]any{"request_status": "existing_requests_retained", "request_count": len(t.requests), "generated": false, "sent": false}), nil
		}
		t.requests = append(t.requests, ReplyMediaRequest{Kind: "image", Intent: args.Intent})
		t.byCall[inv.CallID] = args.Intent
	}
	return CapabilityResult{CallID: inv.CallID, CapabilityName: replyImageRequestName, Status: "completed", Output: map[string]any{
		"request_status": "requested_not_generated", "draft_visibility": "private", "generated": false, "sent": false}}, nil
}

type replyImageRequestInvoker struct{ tool *replyImageRequestTool }

func (i replyImageRequestInvoker) ExecuteWithID(ctx context.Context, id, name, args string) (string, error) {
	if name != replyImageRequestName {
		return "", ErrUnauthorized
	}
	result, err := i.tool.Execute(ctx, CapabilityInvocation{CallID: id, CapabilityName: name, Arguments: json.RawMessage(args)}, CapabilityContext{})
	if err != nil {
		return "", err
	}
	return jsonString(result), nil
}
func (i replyImageRequestInvoker) Execute(ctx context.Context, name, args string) (string, error) {
	return i.ExecuteWithID(ctx, randomID("reply_image_"), name, args)
}
