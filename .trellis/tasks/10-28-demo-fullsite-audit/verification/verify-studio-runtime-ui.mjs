// Fresh self-owned fixture required; never point at live Core.
import {createRequire} from 'node:module';
import {mkdir,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import assert from 'node:assert/strict';
const require=createRequire('/private/tmp/fluctlight-demo-audit-20261028/browser-tools/package.json');
const {chromium}=require('playwright-core');
const base=process.env.STUDIO_RUNTIME_BASE || 'http://127.0.0.1:4453';
assert.equal(new URL(base).hostname,'127.0.0.1');
const out=resolve('.trellis/tasks/10-28-demo-fullsite-audit/evidence/studio-runtime-application');
await mkdir(out,{recursive:true});
const results=[],fid='fluctlight-fixture-one',resource='studio-world';
const browser=await chromium.launch({channel:'chrome',headless:true});
try { for (const [size,width,height] of [['desktop',1348,925],['mobile',390,844]]) {
  const context=await browser.newContext({viewport:{width,height},deviceScaleFactor:1,locale:'zh-CN',timezoneId:'Asia/Shanghai',reducedMotion:'reduce'});
  const page=await context.newPage(); page.setDefaultTimeout(10000);
  const record={size,width,height,dpr:1,boundary:'production components / controlled HTTP in-memory runtime; no live persistence claim',checks:[],requests:[],errors:[],screenshots:[]};
  const check=(name,value)=>{assert.ok(value,name);record.checks.push(name);};
  const get=async path=>{const r=await page.request.get(base+path);assert.equal(r.status(),200,path);return r.json();};
  const dialog=()=>page.getByRole('dialog').last();
  const shot=async name=>{await page.evaluate(async()=>{await document.fonts.ready;await Promise.all(document.getAnimations().filter(a=>a.effect?.getComputedTiming().iterations!==Infinity).map(a=>a.finished.catch(()=>{})));});check(name+': no document overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));const path=resolve(out,size+'-'+name+'.png');await page.screenshot({path,animations:'disabled'});record.screenshots.push(path);};
  page.on('pageerror',e=>record.errors.push(e.message));
  page.on('request',r=>{const path=new URL(r.url()).pathname;if(path.startsWith('/api/'))record.requests.push({path,method:r.method(),body:r.postDataJSON()});});
  try {
    const publication=await get('/api/studio/resources/'+resource+'/versions/draft%3A1');
    const before=await get('/api/fluctlights/'+fid+'/world/catalog');
    const otherBefore=await get('/api/fluctlights/fluctlight-fixture-two/world/catalog');
    await page.goto(base+'/#/studio/edit/'+resource,{waitUntil:'networkidle'});
    await page.getByRole('button',{name:'应用到角色',exact:true}).click();
    await dialog().getByRole('combobox',{name:'目标角色',exact:true}).click();
    await page.getByRole('option').filter({hasText:'林岚'}).click();
    const previewResponse=page.waitForResponse(r=>new URL(r.url()).pathname.endsWith('/apply-preview'));
    await dialog().getByRole('button',{name:'读取应用差异',exact:true}).click();
    const preview=await(await previewResponse).json();
    check('first desktop creates; following mobile sees same runtime',preview.operation===(size==='desktop'?'create':'update'));
    if(preview.runtime_id) await dialog().getByRole('button',{name:'全部采用允许的发布值',exact:true}).click();
    await shot('preview');
    const receiptResponse=page.waitForResponse(r=>new URL(r.url()).pathname.endsWith('/apply')&&r.request().method()==='POST');
    await dialog().getByRole('button',{name:'确认应用所选字段',exact:true}).click();
    const receipt=await(await receiptResponse).json();
    await dialog().getByRole('heading',{name:'原应用回执已核对',exact:true}).waitFor();
    await shot('receipt');
    await dialog().getByRole('button',{name:'查看角色中的结果',exact:true}).click();
    await page.waitForURL('**/#/c/'+fid+'/worlds');
    const card=page.getByTestId('world-card-'+receipt.id);
    await card.waitFor();check('target directory renders exact published name/background',(await card.innerText()).includes(publication.name)&&(await card.innerText()).includes(publication.body.background));
    check('creation does not activate new world',!(await card.innerText()).includes('当前世界'));
    await shot('target-directory');
    await card.getByRole('button',{name:'进入世界 '+publication.name,exact:true}).click();
    await page.getByRole('tab',{name:'世界设定',exact:true}).click();
    await page.getByRole('tabpanel',{name:'世界设定',exact:true}).getByText(publication.body.background,{exact:true}).waitFor();
    await page.getByRole('button',{name:'完整世界资料与来源',exact:true}).click();
    await page.getByRole('button',{name:'当前世界完整记录',exact:true}).click();
    const body=await page.locator('body').innerText();check('actual target detail renders source id and immutable version',body.includes(resource)&&body.includes(publication.version));
    await shot('target-settings-source');
    await page.reload({waitUntil:'networkidle'});
    await page.getByTestId('world-card-'+receipt.id).waitFor();
    await page.getByTestId('world-card-'+receipt.id).getByRole('button',{name:'进入世界 '+publication.name,exact:true}).click();
    await page.getByRole('tab',{name:'世界设定',exact:true}).click();
    await page.getByRole('tabpanel',{name:'世界设定',exact:true}).getByText(publication.body.background,{exact:true}).waitFor();
    await shot('target-refreshed');
    const after=await get('/api/fluctlights/'+fid+'/world/catalog');
    const actual=await get('/api/fluctlights/'+fid+'/world/catalog/'+receipt.id);
    check('same role runtime source and body survive page refresh',actual.world.source_resource_id===resource&&actual.world.source_version===publication.version&&actual.world.background===publication.body.background);
    check('binding unchanged by applying and browsing',JSON.stringify(before.active_binding)===JSON.stringify(after.active_binding));
    check('framework concrete place materialized once',actual.places.filter(p=>p.name==='书房').length===1);
    check('other role unaffected',JSON.stringify(otherBefore)===JSON.stringify(await get('/api/fluctlights/fluctlight-fixture-two/world/catalog')));
    const source=await get('/api/studio/resources/'+resource);
    check('source references real runtime id',source.referenced_by.some(r=>r.runtime_id===receipt.id&&r.fluctlight_id===fid&&r.running_version===publication.version));
    await page.goto(base+'/#/studio/edit/'+resource,{waitUntil:'networkidle'});
    await page.getByRole('button',{name:'应用到角色',exact:true}).click();
    const againResponse=page.waitForResponse(r=>new URL(r.url()).pathname.endsWith('/apply-preview'));
    await dialog().getByRole('button',{name:'读取应用差异',exact:true}).click();
    const again=await(await againResponse).json();
    check('repreview targets same existing runtime',again.runtime_id===receipt.id&&!again.create_required&&['update','unchanged'].includes(again.operation));
    check('one apply mutation per viewport',record.requests.filter(r=>r.method==='POST'&&r.path.endsWith('/apply')).length===1);
    check('no browser exceptions',record.errors.length===0);record.status='passed';
  } catch(e) {record.status='failed';record.error=e.stack;record.text=await page.locator('body').innerText().catch(()=>null);await shot('failure').catch(()=>{});}
  results.push(record);await writeFile(resolve(out,'report.json'),JSON.stringify(results,null,2)+'\n');console.log(size,record.status,record.error||record.checks.length);await context.close();
}} finally {await browser.close();}
if(results.some(r=>r.status!=='passed'))process.exitCode=1;
